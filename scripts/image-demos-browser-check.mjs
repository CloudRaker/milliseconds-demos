// QA_BASE=http://127.0.0.1:4324 PLAYWRIGHT_MODULE=/path/to/playwright/index.mjs node scripts/image-demos-browser-check.mjs
// Browser integration checks use explicit mock responses, never claim model accuracy.
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.QA_BASE || 'http://127.0.0.1:4324';
const output = process.env.QA_OUTPUT || '/tmp/ms-image-demos-qa';
await mkdir(output, { recursive: true });
const catalog = JSON.parse(await readFile(new URL('../src/generated/examples.json', import.meta.url)));
const slugs = ['waste-sorter', 'crack-check', 'leaf-check', 'land-cover', 'roast-check', 'produce-check'];
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('https://console.milliseconds.ai/**', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{}' }));
let calls = [], mode = 'success', release;
await page.route('**/api/examples/**', async route => {
  const id = new URL(route.request().url()).pathname.slice('/api/examples/'.length);
  const entry = catalog[id];
  assert.ok(entry, `registered stock request: ${id}`);
  assert.ok(entry.body.image.startsWith('data:image/'));
  assert.equal(entry.body.text, undefined, 'source label is never input text');
  assert.deepEqual(route.request().postDataJSON(), {});
  calls.push(id);
  if (mode === 'hold') await new Promise(resolve => { release = resolve; });
  if (mode === 'failure') return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'qa_failure', message: 'QA service unavailable' } }) });
  const labels = Object.keys(entry.body.labels);
  await route.fulfill({ contentType: 'application/json', headers: { 'x-demo-source': 'cache', 'x-input-tokens': '1000', 'x-inference-ms': '12' }, body: JSON.stringify({ label: labels[0], probability: .9, scores: Object.fromEntries(labels.map((label, index) => [label, index ? .1 / (labels.length - 1) : .9])) }) }).catch(() => {});
});
try {
  await page.goto(`${base}/?input=image`);
  await page.locator('[data-input-filter=image][aria-pressed=true]').waitFor();
  assert.equal(await page.locator('.demo-card:visible').count(), 8);
  assert.equal(await page.locator('.demo-card:visible[data-input=text]').count(), 0);
  assert.equal(await page.locator('.demo-card:visible[href="/hot-dog/"]').count(), 1);
  assert.equal(await page.locator('.demo-card:visible[href="/receipt-reader/"]').count(), 1);
  await page.screenshot({ path: `${output}/catalog-desktop.png`, fullPage: true });
  await page.locator('[data-demo-filter="Customer experience"]').click();
  assert.equal(await page.locator('.demo-card:visible').count(), 0);
  await page.locator('.demo-filter-empty:not([hidden])').waitFor();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  assert.equal(await page.locator('.demo-card:visible').count(), new Set(Object.values(catalog).map(entry => entry.demo)).size);
  await page.goBack();
  await page.locator('.demo-filter-empty:not([hidden])').waitFor();
  await page.goBack();
  await page.locator('[data-input-filter=image][aria-pressed=true]').waitFor();
  assert.equal(await page.locator('.demo-card:visible').count(), 8);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'catalog mobile overflow');
  await page.screenshot({ path: `${output}/catalog-mobile.png`, fullPage: true });
  for (const slug of slugs) {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`${base}/${slug}/`);
    await page.locator('.image-classifier').waitFor();
    await page.locator('.ic-image img').evaluate(image => image.decode());
    assert.equal(await page.locator('.ic-tile').count(), Object.values(catalog).filter(entry => entry.demo === slug).length);
    assert.equal(await page.locator('.ic-scores li').count(), 0, 'no fabricated initial result');
    calls = [];
    await page.getByRole('button', { name: 'Classify this image', exact: true }).click();
    await page.locator('.ic-scores li').first().waitFor();
    assert.equal(calls.length, 1);
    assert.ok(await page.locator('.ic-annotation strong').innerText());
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.screenshot({ path: `${output}/${slug}-desktop.png`, fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${slug} mobile overflow`);
    await page.screenshot({ path: `${output}/${slug}-mobile.png`, fullPage: true });
    await page.locator('.ic-tile').nth(1).click();
    assert.equal(await page.locator('.ic-scores li').count(), 0, 'switching images does not reuse another result');
    console.log(`PASS ${slug}: real images render, stock request resolves, isolated results, desktop/mobile layout`);
  }
  calls = [];
  await page.getByRole('button', { name: 'Classify sample set', exact: true }).click();
  await page.locator('.ic-status').filter({ hasText: '6 photos classified.' }).waitFor();
  assert.equal(calls.length, 6, 'sample set runs every photo once');
  assert.equal(await page.locator('.ic-tile-state.has-result').count(), 6);
  mode = 'failure';
  await page.getByRole('button', { name: 'Classify this image', exact: true }).click();
  await page.locator('.ic-status.is-error').waitFor();
  assert.match(await page.locator('.ic-status').innerText(), /QA service unavailable/);
  mode = 'hold';
  const pendingRequest = page.waitForRequest('**/api/examples/**');
  await page.getByRole('button', { name: 'Classify this image', exact: true }).click();
  await pendingRequest;
  await page.getByRole('button', { name: 'Stop', exact: true }).click();
  mode = 'success'; release();
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await page.locator('.ic-scores li').count(), 0);
  const entry = Object.values(catalog).find(entry => entry.demo === 'waste-sorter');
  await page.locator('.ic-actions input[type=file]').setInputFiles({ name: 'photo.jpg', mimeType: 'image/jpeg', buffer: Buffer.from(entry.body.image.split(',')[1], 'base64') });
  await page.locator('.ic-annotation strong').filter({ hasText: 'Your image' }).waitFor();
  await page.getByRole('button', { name: 'Classify this image', exact: true }).click();
  await page.locator('.ic-status.is-error').waitFor();
  assert.match(await page.locator('.ic-status').innerText(), /API key/);
  assert.match(await page.locator('.ic-preview figcaption').innerText(), /Your photo/);
  await page.locator('.ic-actions input[type=file]').setInputFiles({ name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image') });
  await page.locator('.ic-status.is-error').waitFor();
  assert.match(await page.locator('.ic-status').innerText(), /JPEG|PNG|WebP/);
  assert.deepEqual(errors, []);
  console.log('PASS filters/deep links/back/reset, request errors, cancellation, upload/key flow, invalid files; inference mocked.');
} finally { await browser.close(); }
